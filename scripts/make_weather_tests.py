"""Runs the tool-level weather cases and writes tests/weather_tool_tests.md with the real outputs.
Run from the repository root:  python scripts/make_weather_tests.py
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ["WEATHER_MODE"] = "stub"

from tools.weather import get_weather   # noqa: E402

CASES = [
    ("T1", "Mumbai, 2026-05-15 (check value: 26, 43, 10, 0.0)", "Mumbai", "2026-05-15"),
    ("T2", "Pune, 2026-05-16 (check value: 25, 88, 11, 6.5)", "Pune", "2026-05-16"),
    ("T3", "Hyderabad, 2026-04-01 (check value: 30, 58, 6, 0.0)", "Hyderabad", "2026-04-01"),
    ("T4", "Unsupported city", "Kolkata", "2026-05-15"),
    ("T5", "Date that is not a real calendar date", "Pune", "2026-02-30"),
    ("T6", "Date in the wrong format", "Pune", "15 May 2026"),
    ("T7", "Bengaluru on a day number divisible by 4 (rain expected)", "Bengaluru", "2026-06-29"),
]

lines = ["# Weather tool tests (WEATHER_MODE=stub)", "",
         "Generated by `python scripts/make_weather_tests.py`. Each output is pasted from a real call.", ""]
for cid, what, city, d in CASES:
    out = get_weather(city, d)
    lines += [f"## {cid}: {what}", "", f"Call: `get_weather({city!r}, {d!r})`", "",
              "```", json.dumps(out), "```", ""]
    print(cid, json.dumps(out))
(ROOT / "tests").mkdir(exist_ok=True)
(ROOT / "tests" / "weather_tool_tests.md").write_text("\n".join(lines), encoding="utf-8")